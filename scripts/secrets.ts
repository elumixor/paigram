/**
 * Writes `submodules/PaiUI/Sources/PaiSecrets.swift` (gitignored) with the box's address and the bot's name, neither
 * of them secret: the app holds no credential of its own, each phone signs in and gets a device token
 * (`PaiAuth`). On a developer's Mac the address comes from the box the `pai` CLI already knows
 * (`~/.config/pai/box.json`); on CI, where there is no box file, from `PAI_BOX_URL` (and `PAI_BOT_USERNAME`).
 */
import { homedir } from "node:os";
import { secretsPath } from "./repo.ts";

const boxFile = `${homedir()}/.config/pai/box.json`;

async function boxUrl(): Promise<string> {
  if (process.env.PAI_BOX_URL) return process.env.PAI_BOX_URL;
  const box = Bun.file(boxFile);
  if (!(await box.exists())) throw new Error(`${boxFile} is missing: run any \`pai\` command once so it learns the box, or set PAI_BOX_URL`);
  const { url } = (await box.json()) as { url?: string };
  if (!url) throw new Error(`${boxFile} has no url`);
  return url;
}

/** The box knows which bot it talks through; `/m/telegram/info` is public. */
export async function fetchBotUsername(url: string): Promise<string> {
  const info = await fetch(`${url}/m/telegram/info`);
  if (!info.ok) throw new Error(`${url}/m/telegram/info answered HTTP ${info.status}: is the telegram module running?`);
  const { botUsername } = (await info.json()) as { botUsername?: string };
  if (!botUsername) throw new Error("the box does not know its bot username yet");
  return botUsername;
}

export async function writeSecrets() {
  const url = await boxUrl();
  // `PAI_BOT_USERNAME` saves CI a round trip to a box it may not reach.
  const bot = process.env.PAI_BOT_USERNAME ?? (await fetchBotUsername(url));
  await Bun.write(
    secretsPath,
    `// Generated by scripts/secrets.ts from the box. Not committed.\npublic enum PaiSecrets {\n    public static let baseURL = ${JSON.stringify(url)}\n    public static let botUsername = ${JSON.stringify(bot)}\n}\n`,
  );
}

if (import.meta.main) await writeSecrets();
